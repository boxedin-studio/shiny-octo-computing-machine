#!/usr/bin/env node
/*
  build.js  -  turns projects.js into the real pages of the site.

  Run it with:   node build.js
  (Claude runs this for you when you say COMMIT.)

  It reads projects.js and the two templates in _templates/, and writes:
    index.html                      the home page (project lists are real HTML)
    architecture-1.html ...         one page per project in projects.js
    sitemap.xml and robots.txt      so search engines can find every page
  Any old project page that is no longer in projects.js is replaced with a small redirect to the home page.

  Do not edit the generated pages by hand: the next build replaces them.
  To change how pages look, edit _templates/ and project.css.
*/
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm');
const ROOT = __dirname;
const SITE_URL = 'https://boxedin.studio';
const STATIC_PAGES = ['studio.html', 'archive.html', 'journal.html']; // hand-written pages listed in the sitemap
const PLACEHOLDER = /Short description of the project goes here/;

// ---- read the data -------------------------------------------------------
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'projects.js'), 'utf8'), ctx, { filename: 'projects.js' });
const SITE = ctx.window.SITE;
if (!SITE || !Array.isArray(SITE.projects) || !Array.isArray(SITE.mediums)) throw new Error('projects.js must define window.SITE with mediums and projects');

// ---- helpers -------------------------------------------------------------
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const titleCase = s => String(s).replace(/(^|\s)\S/g, c => c.toUpperCase());
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');
const write = (f, t) => fs.writeFileSync(path.join(ROOT, f), t);
const fill = (tpl, vars) => tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => { if (!(k in vars)) throw new Error('Template needs ' + k); return vars[k]; });
const GENERATED = '<!-- Generated by build.js from projects.js and _templates/. Edit those, not this file. -->\n';
const withBanner = html => html.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + GENERATED);
function shorten(text, max) {
  const t = String(text).replace(/\s+/g, ' ').trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max - 1), sp = cut.lastIndexOf(' ');
  return (sp > 80 ? cut.slice(0, sp) : cut).replace(/[ ,.;:]+$/, '') + '…';
}

// ---- checks --------------------------------------------------------------
const ids = new Set(), warnings = [];
SITE.projects.forEach(p => {
  if (!p.id || !p.medium || !p.name || !p.color) throw new Error('Every project needs id, medium, name and color: ' + JSON.stringify(p.id || p));
  if (ids.has(p.id)) throw new Error('Duplicate project id: ' + p.id);
  ids.add(p.id);
  if (!SITE.mediums.some(m => m.id === p.medium)) throw new Error(p.id + ' uses an unknown medium: ' + p.medium);
  if (!/^#[0-9a-f]{6}$/i.test(p.color)) throw new Error(p.id + ' colour must look like #56704f');
  const todo = [];
  if (PLACEHOLDER.test(p.description || '')) todo.push('description');
  if ((p.details || []).some(kv => ['0000', 'materials', 'location', 'type', '$0'].includes(kv[1]))) todo.push('details');
  if (!(p.images || []).length) todo.push('photos');
  if (todo.length) warnings.push(p.name.padEnd(20) + ' still needs: ' + todo.join(', '));
});

// ---- home page -----------------------------------------------------------
const tabs = SITE.mediums.map(m => `<a href="#${esc(m.id)}" data-tab="${esc(m.id)}">${esc(m.label)}</a>`).join('');
const groups = SITE.mediums.map(m => {
  const items = SITE.projects.filter(p => p.medium === m.id).map((p, i) =>
    `<li style="--i:${i}"><a href="${esc(p.id)}.html" data-bg="${esc(p.color)}">${esc(p.name)}</a></li>`);
  return `<ul class="group" data-tab="${esc(m.id)}" aria-label="${esc(m.label)} projects"><li class="group-title">${esc(m.label)}</li>${items.join('')}</ul>`;
}).join('\n    ');
write('index.html', withBanner(fill(read('_templates/index.html'), { TABS: tabs, GROUPS: groups })));

// ---- project pages -------------------------------------------------------
const projectTpl = read('_templates/project.html');
function imageOf(im) { return typeof im === 'string' ? { src: im } : im; }
function bodyFor(p) {
  const out = [];
  const paras = String(p.description || '').split(/\n\s*\n/).map(t => t.trim()).filter(Boolean);
  if (paras.length) out.push('    <div class="desc">\n' + paras.map(t => '      <p>' + esc(t) + '</p>').join('\n') + '\n    </div>');
  if ((p.details || []).length) out.push('    <dl class="details">\n' + p.details.map(kv => `      <div><dt>${esc(kv[0])}</dt><dd>${esc(kv[1])}</dd></div>`).join('\n') + '\n    </dl>');
  const imgs = (p.images || []).map(imageOf);
  if (imgs.length) {
    out.push('    <div class="gallery">\n' + imgs.map((im, i) => {
      const alt = im.alt || (titleCase(p.name) + ' – image ' + (i + 1));
      const size = im.w && im.h ? ` width="${Number(im.w)}" height="${Number(im.h)}"` : '';
      const load = i === 0 ? ' fetchpriority="high"' : ' loading="lazy"';
      return `      <figure><img src="${esc(im.src)}" alt="${esc(alt)}"${size}${load} decoding="async"></figure>`;
    }).join('\n') + '\n    </div>');
  } else {
    out.push('    <div class="gallery" aria-hidden="true">\n' + [0, 1, 2, 3].map(() => '      <figure class="ph"></figure>').join('\n') + '\n    </div>');
  }
  const sib = SITE.projects.filter(x => x.medium === p.medium), k = sib.indexOf(p), links = [];
  if (k > 0) links.push(`      <a class="ul prev" href="${esc(sib[k - 1].id)}.html"><small>previous</small><span>${esc(sib[k - 1].name)}</span></a>`);
  if (k < sib.length - 1) links.push(`      <a class="ul next" href="${esc(sib[k + 1].id)}.html"><small>next</small><span>${esc(sib[k + 1].name)}</span></a>`);
  if (links.length) out.push(`    <nav class="pager" aria-label="More ${esc(p.medium)} projects">\n${links.join('\n')}\n    </nav>`);
  return out.join('\n');
}
const generated = new Set();
SITE.projects.forEach(p => {
  const first = (p.images || []).map(imageOf)[0];
  const title = titleCase(p.name) + (p.place ? ', ' + p.place : '') + ' — Boxed In Studio';
  const firstPara = String(p.description || '').split(/\n\s*\n/)[0];
  const desc = shorten(firstPara && !PLACEHOLDER.test(firstPara) ? firstPara : titleCase(p.name) + ' by Boxed In Studio.', 155);
  const ogImage = first ? SITE_URL + '/' + String(first.src).replace(/^\//, '') : SITE_URL + '/og-image.png';
  write(p.id + '.html', withBanner(fill(projectTpl, {
    COLOR: esc(p.color), TITLE: esc(title), DESC_META: esc(desc), URL: SITE_URL + '/' + p.id + '.html',
    OG_IMAGE: esc(ogImage), NAME: esc(p.name), BODY: bodyFor(p)
  })));
  generated.add(p.id + '.html');
});

// ---- old project pages that are no longer in projects.js -----------------
const stub = '<!DOCTYPE html>\n' + GENERATED + '<html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex"><meta http-equiv="refresh" content="0;url=index.html"><link rel="canonical" href="' + SITE_URL + '/"><title>Boxed In Studio</title></head><body><a href="index.html">Boxed In Studio</a></body></html>\n';
const stubbed = [];
fs.readdirSync(ROOT).filter(f => /^[a-z]+-\d+\.html$/.test(f) && !generated.has(f)).forEach(f => { write(f, stub); stubbed.push(f); });

// ---- sitemap and robots --------------------------------------------------
const urls = ['', ...STATIC_PAGES, ...[...generated]].map(u => `  <url><loc>${SITE_URL}/${u}</loc></url>`).join('\n');
write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);
write('robots.txt', `User-agent: *\nAllow: /\nDisallow: /_templates/\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

// ---- report --------------------------------------------------------------
console.log(`Built index.html and ${generated.size} project pages, sitemap.xml, robots.txt.`);
if (stubbed.length) console.log(`Unused pages turned into redirects: ${stubbed.join(', ')}`);
if (warnings.length) console.log('\nStill to fill in (this is fine while you are setting up):\n  ' + warnings.join('\n  '));
