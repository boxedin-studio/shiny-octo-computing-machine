#!/usr/bin/env node
/*
  build.js  -  turns projects.js (and your photos) into the real pages of the site.

  Run it with:   node source/build.js        (Claude runs this for you when you say COMMIT)

  It reads source/projects.js, the templates in source/templates/ and the originals in source/photos/, and writes:
    index.html                              the home page (project lists are real HTML)
    projects/<medium>/<project-name>/       one page per project, at a clean address such as /projects/carpentry/ply-table/
    assets/photos/<project-name>/           cropped and resized copies of your photos (your originals are never touched)
    404.html                                friendly "not found" page, which also forwards old addresses to the right page
    sitemap.xml and robots.txt              so search engines can find every page

  Do not edit the generated pages by hand: the next build replaces them.
  To change how pages look, edit source/templates/ and assets/css/project.css.
*/
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), crypto = require('crypto');
const SRC = __dirname, ROOT = path.join(SRC, '..');
const SITE_URL = 'https://boxedin.studio';
const STATIC_PAGES = ['archive', 'studio', 'journal'];           // hand-written pages (folders in the main folder)
const PLACEHOLDER = /Short description of the project goes here/;
// Photo shapes. In each group of three cells the 1st is landscape, the 2nd and 3rd are squares.
// (If you change the landscape ratio here, change the 3/2 for .gallery figure:nth-child(3n+1) in assets/css/project.css too.)
const LANDSCAPE = 3 / 2;
const WIDTHS = { L: [900, 1720], S: [480, 900] };               // sizes made for the page (phones get the smaller one)
const FULL_MAX = 2400;                                           // the enlarged view: longest side in pixels

let sharp;
try { sharp = require('sharp'); } catch (e) { sharp = null; }

// ---- read the data -------------------------------------------------------
const ctx = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(SRC, 'projects.js'), 'utf8'), ctx, { filename: 'projects.js' });
const SITE = ctx.window.SITE;
if (!SITE || !Array.isArray(SITE.projects) || !Array.isArray(SITE.mediums)) throw new Error('projects.js must define window.SITE with mediums and projects');

// ---- helpers -------------------------------------------------------------
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
const titleCase = s => String(s).replace(/(^|\s)\S/g, c => c.toUpperCase());
const slugify = s => String(s).normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/&/g, ' and ').replace(/['’]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const readSrc = f => fs.readFileSync(path.join(SRC, f), 'utf8');
const writeRoot = (f, t) => { const p = path.join(ROOT, f); fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, t); };
const fill = (tpl, vars) => tpl.replace(/\{\{(\w+)\}\}/g, (_, k) => { if (!(k in vars)) throw new Error('Template needs ' + k); return vars[k]; });
const GENERATED = '<!-- Generated by source/build.js from source/projects.js and source/templates/. Edit those, not this file. -->\n';
const withBanner = html => html.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + GENERATED);
function shorten(text, max) {
  const t = String(text).replace(/\s+/g, ' ').trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max - 1), sp = cut.lastIndexOf(' ');
  return (sp > 80 ? cut.slice(0, sp) : cut).replace(/[ ,.;:]+$/, '') + '…';
}
const isText = im => typeof im === 'object' && im && (im.text != null || im.title != null) && !im.src;
const itemOf = im => typeof im === 'string' ? { src: im } : im;

// ---- checks and addresses ------------------------------------------------
const warnings = [], ids = new Set();
const slugsFile = path.join(SRC, 'slugs.json');
const slugRecord = fs.existsSync(slugsFile) ? JSON.parse(fs.readFileSync(slugsFile, 'utf8')) : {};
const taken = new Set();
SITE.projects.forEach(p => {
  if (!p.id || !p.medium || !p.name || !p.color) throw new Error('Every project needs id, medium, name and color: ' + JSON.stringify(p.id || p));
  if (ids.has(p.id)) throw new Error('Duplicate project id: ' + p.id);
  ids.add(p.id);
  if (!SITE.mediums.some(m => m.id === p.medium)) throw new Error(p.id + ' uses an unknown medium: ' + p.medium);
  if (!/^#[0-9a-f]{6}$/i.test(p.color)) throw new Error(p.id + ' colour must look like #56704f');
  p.slug = slugify(p.slug || p.name);
  if (!p.slug) throw new Error(p.id + ': the name has no letters or numbers to make an address from. Add slug:"something" to the project.');
  const key = p.medium + '/' + p.slug;
  if (taken.has(key)) throw new Error('Two ' + p.medium + ' projects would share the address /projects/' + key + '/ . Give one of them a different name (or add slug:"…").');
  taken.add(key);
  p.path = 'projects/' + p.medium + '/' + p.slug + '/';
  const rec = slugRecord[p.id] || (slugRecord[p.id] = { current: p.slug, old: [] });
  if (rec.current !== p.slug) { if (!rec.old.includes(rec.current)) rec.old.push(rec.current); rec.current = p.slug; }
  rec.old = rec.old.filter(s => s !== p.slug);
});

// ---- photos --------------------------------------------------------------
const usedFiles = new Set(), photoNotes = [];
const hashOf = (...parts) => crypto.createHash('sha1').update(parts.join('|')).digest('hex').slice(0, 8);
function parseFocus(f) {
  const words = { left: 0, top: 0, center: 50, right: 100, bottom: 100 };
  const parts = String(f || '50% 50%').trim().split(/\s+/).map(t => t in words ? words[t] : parseFloat(t));
  const x = isFinite(parts[0]) ? parts[0] : 50, y = isFinite(parts[1]) ? parts[1] : 50;
  return [Math.min(100, Math.max(0, x)) / 100, Math.min(100, Math.max(0, y)) / 100];
}
async function ensure(rel, make) {                  // make the file if it is not there yet; return its size
  const abs = path.join(ROOT, rel);
  usedFiles.add(rel);
  if (!fs.existsSync(abs)) { fs.mkdirSync(path.dirname(abs), { recursive: true }); await make(abs); }
  const m = await sharp(abs).metadata();
  return { url: rel, w: m.width, h: m.height };
}
async function makePhoto(p, im, shape) {
  const file = path.join(SRC, 'photos', im.src);
  if (!fs.existsSync(file)) { photoNotes.push(p.name + ': photo not found, left out: source/photos/' + im.src); return null; }
  if (!sharp) throw new Error('The image tool (sharp) is not installed. Run: cd source && npm install');
  const bytes = fs.readFileSync(file), h8 = hashOf(bytes.length, crypto.createHash('sha1').update(bytes).digest('hex'));
  const stem = slugify(path.basename(im.src, path.extname(im.src))) || 'photo';
  const dir = 'assets/photos/' + p.slug + '/';
  const oriented = await sharp(bytes).rotate().toBuffer();             // applies the phone's rotation flag
  const { width: W, height: H } = await sharp(oriented).metadata();
  const ratio = shape === 'L' ? LANDSCAPE : 1;
  let cw, ch; if (W / H > ratio) { ch = H; cw = Math.round(H * ratio); } else { cw = W; ch = Math.round(W / ratio); }
  const [fx, fy] = parseFocus(im.focus);
  const left = Math.round((W - cw) * fx), top = Math.round((H - ch) * fy);
  const fh = hashOf(h8, left, top, cw, ch, shape);
  const widths = [...new Set(WIDTHS[shape].map(w => Math.min(w, cw)))].sort((a, b) => a - b);
  const thumbs = [];
  for (const w of widths) {
    const h = Math.round(w / ratio);
    thumbs.push(await ensure(dir + stem + '-' + shape.toLowerCase() + '-' + w + '-' + fh + '.jpg', abs =>
      sharp(oriented).extract({ left, top, width: cw, height: ch }).resize(w, h).jpeg({ quality: 80, mozjpeg: true, progressive: true }).toFile(abs)));
  }
  const full = await ensure(dir + stem + '-full-' + h8 + '.jpg', abs =>
    sharp(oriented).resize({ width: FULL_MAX, height: FULL_MAX, fit: 'inside', withoutEnlargement: true }).jpeg({ quality: 85, mozjpeg: true, progressive: true }).toFile(abs));
  if (Math.max(W, H) < 1600) photoNotes.push(p.name + ': ' + im.src + ' is only ' + W + '×' + H + ' pixels, so the enlarged view will be soft. Use the original from your camera if you have it.');
  return { thumbs, full };
}

// ---- gallery and page body -----------------------------------------------
async function bodyFor(p, base) {
  const out = [];
  const paras = String(p.description || '').split(/\n\s*\n/).map(t => t.trim()).filter(Boolean);
  if (paras.length) out.push('    <div class="desc">\n' + paras.map(t => '      <p>' + esc(t) + '</p>').join('\n') + '\n    </div>');
  if ((p.details || []).length) out.push('    <dl class="details">\n' + p.details.map(kv => `      <div><dt>${esc(kv[0])}</dt><dd>${esc(kv[1])}</dd></div>`).join('\n') + '\n    </dl>');
  const items = (p.images || []).map(itemOf);
  const figs = []; let ogImage = null, photoNo = 0, noAlt = 0, cell = 0;
  for (const im of items) {
    const shape = cell % 3 === 0 ? 'L' : 'S';
    if (isText(im)) {
      const body = String(im.text || '').split(/\n\s*\n/).map(t => t.trim()).filter(Boolean).map(t => '<p>' + esc(t) + '</p>').join('');
      figs.push(`      <figure class="txt"><div>${im.title ? '<h2>' + esc(im.title) + '</h2>' : ''}${body}</div></figure>`);
      cell++; continue;
    }
    const made = await makePhoto(p, im, shape);
    if (!made) continue;
    photoNo++; if (!im.alt) noAlt++;
    const alt = im.alt || (titleCase(p.name) + ' – photo ' + photoNo);
    const big = made.thumbs[made.thumbs.length - 1];
    const srcset = made.thumbs.map(t => base + t.url + ' ' + t.w + 'w').join(', ');
    const sizes = shape === 'L' ? '(min-width:924px) 860px, 100vw' : '(min-width:924px) 400px, (min-width:624px) 45vw, 100vw';
    const load = ogImage ? ' loading="lazy"' : ' fetchpriority="high"';
    figs.push(`      <figure><a class="zoom" href="${base + made.full.url}" aria-label="Open photo ${photoNo} larger"><img src="${base + big.url}" srcset="${srcset}" sizes="${sizes}" width="${big.w}" height="${big.h}" alt="${esc(alt)}"${load} decoding="async"></a></figure>`);
    if (!ogImage) ogImage = SITE_URL + '/' + big.url;
    cell++;
  }
  if (figs.length) out.push('    <div class="gallery">\n' + figs.join('\n') + '\n    </div>');
  else out.push('    <div class="gallery" aria-hidden="true">\n' + [0, 1, 2, 3].map(() => '      <figure class="ph"></figure>').join('\n') + '\n    </div>');
  const sib = SITE.projects.filter(x => x.medium === p.medium), k = sib.indexOf(p), links = [];
  if (k > 0) links.push(`      <a class="ul prev" href="../${esc(sib[k - 1].slug)}/"><small>previous</small><span>${esc(sib[k - 1].name)}</span></a>`);
  if (k < sib.length - 1) links.push(`      <a class="ul next" href="../${esc(sib[k + 1].slug)}/"><small>next</small><span>${esc(sib[k + 1].name)}</span></a>`);
  if (links.length) out.push(`    <nav class="pager" aria-label="More ${esc(p.medium)} projects">\n${links.join('\n')}\n    </nav>`);
  return { html: out.join('\n'), ogImage, noAlt, photos: photoNo };
}

(async () => {
  // ---- home page ---------------------------------------------------------
  const tabs = SITE.mediums.map(m => `<a href="#${esc(m.id)}" data-tab="${esc(m.id)}">${esc(m.label)}</a>`).join('');
  const groups = SITE.mediums.map(m => {
    const items = SITE.projects.filter(p => p.medium === m.id).map((p, i) =>
      `<li style="--i:${i}"><a href="${esc(p.path)}" data-bg="${esc(p.color)}">${esc(p.name)}</a></li>`);
    return `<ul class="group" data-tab="${esc(m.id)}" aria-label="${esc(m.label)} projects"><li class="group-title">${esc(m.label)}</li>${items.join('')}</ul>`;
  }).join('\n    ');
  writeRoot('index.html', withBanner(fill(readSrc('templates/index.html'), { TABS: tabs, GROUPS: groups })));

  // ---- project pages -----------------------------------------------------
  fs.rmSync(path.join(ROOT, 'projects'), { recursive: true, force: true });
  const projectTpl = readSrc('templates/project.html');
  for (const p of SITE.projects) {
    const base = '../../../';
    const body = await bodyFor(p, base);
    const todo = [];
    if (PLACEHOLDER.test(p.description || '')) todo.push('description');
    if ((p.details || []).some(kv => ['0000', 'materials', 'location', 'type', '$0'].includes(kv[1]))) todo.push('details');
    if (!body.photos) todo.push('photos'); else if (body.noAlt) todo.push('photo descriptions (alt)');
    if (todo.length) warnings.push(p.name.padEnd(20) + ' still needs: ' + todo.join(', '));
    const title = titleCase(p.name) + (p.place ? ', ' + p.place : '') + ' — Boxed In Studio';
    const firstPara = String(p.description || '').split(/\n\s*\n/)[0];
    const desc = shorten(firstPara && !PLACEHOLDER.test(firstPara) ? firstPara : titleCase(p.name) + ' by Boxed In Studio.', 155);
    writeRoot(p.path + 'index.html', withBanner(fill(projectTpl, {
      BASE: base, MEDIUM: esc(p.medium), COLOR: esc(p.color), TITLE: esc(title), DESC_META: esc(desc), URL: SITE_URL + '/' + p.path,
      OG_IMAGE: esc(body.ogImage || SITE_URL + '/assets/img/og-image.png'), NAME: esc(p.name), BODY: body.html
    })));
  }

  // ---- tidy up photos that are no longer used ----------------------------
  const photoRoot = path.join(ROOT, 'assets/photos');
  (function sweep(dir) {
    if (!fs.existsSync(dir)) return;
    for (const f of fs.readdirSync(dir)) {
      const abs = path.join(dir, f);
      if (fs.statSync(abs).isDirectory()) { sweep(abs); if (!fs.readdirSync(abs).length) fs.rmdirSync(abs); }
      else if (!usedFiles.has(path.relative(ROOT, abs).split(path.sep).join('/'))) fs.unlinkSync(abs);
    }
  })(photoRoot);

  // ---- old addresses that forward to the new ones ------------------------
  const redirects = {};
  SITE.projects.forEach(p => {
    redirects[p.id] = '/' + p.path;                                         // the old address, e.g. /carpentry-1.html
    slugRecord[p.id].old.forEach(s => { redirects['projects/' + p.medium + '/' + s] = '/' + p.path; });
  });
  STATIC_PAGES.forEach(s => { redirects[s] = '/' + s + '/'; });
  writeRoot('404.html', fill(readSrc('templates/404.html'), { REDIRECTS: JSON.stringify(redirects) }));
  fs.writeFileSync(slugsFile, JSON.stringify(slugRecord, null, 2) + '\n');
  // old numbered pages in the main folder (carpentry-1.html and so on) are no longer used
  const legacy = fs.readdirSync(ROOT).filter(f => /^[a-z]+-\d+\.html$/.test(f));
  legacy.forEach(f => fs.unlinkSync(path.join(ROOT, f)));

  // ---- sitemap and robots ------------------------------------------------
  const urls = ['', ...STATIC_PAGES.map(s => s + '/'), ...SITE.projects.map(p => p.path)].map(u => `  <url><loc>${SITE_URL}/${u}</loc></url>`).join('\n');
  writeRoot('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);
  writeRoot('robots.txt', `User-agent: *\nAllow: /\nDisallow: /source/\n\nSitemap: ${SITE_URL}/sitemap.xml\n`);

  // ---- report ------------------------------------------------------------
  console.log(`Built index.html, ${SITE.projects.length} project pages, 404.html, sitemap.xml, robots.txt.`);
  if (legacy.length) console.log('Removed old numbered pages: ' + legacy.join(', '));
  if (photoNotes.length) console.log('\nPhotos:\n  ' + photoNotes.join('\n  '));
  if (warnings.length) console.log('\nStill to fill in (this is fine while you are setting up):\n  ' + warnings.join('\n  '));
})().catch(e => { console.error('\nBuild stopped: ' + e.message); process.exit(1); });
